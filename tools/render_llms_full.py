#!/usr/bin/env python3
"""Render site/llms-full.txt — the full-content companion to llms.txt.

Convention (llmstxt.org ecosystem): /llms.txt is an index of links;
/llms-full.txt inlines the actual markdown content of the linked pages so
an agent can load the whole surface in one fetch. Generated at build time —
never hand-edit the output.

Sources are local repo files (single sources of truth) plus the hosted
meter's own llms.txt fetched live; if the fetch fails the hosted section is
omitted and a warning is printed — the file must still build offline.
"""
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SITE = os.path.join(HERE, "..", "site")
HEADS = os.path.abspath(os.path.join(HERE, "..", "..", "mtlm-heads"))
INDEX = os.path.join(HEADS, "index.json")
PRICING = os.path.join(HEADS, "PRICING.md")
README = os.path.join(HERE, "..", "README.md")
OPENAPI = os.path.join(HERE, "..", "ops", "openapi.yaml")
OUT = os.path.join(SITE, "llms-full.txt")
HOSTED_LLMS = "https://api.mtlm-router.intrane.fr/llms.txt"


def read(p):
    with open(p) as f:
        return f.read().strip()


def lane_summary():
    with open(INDEX) as f:
        lanes = json.load(f)["lanes"]
    live = [p for p in lanes
            if not p.get("yanked") and not p.get("superseded_by")]
    lines = []
    for p in sorted(live, key=lambda x: x["name"]):
        floor = (p.get("operating") or {}).get("min_conf")
        floor_s = f"floor conf>={floor}" if floor is not None else "argmax carries"
        acc = p.get("holdout_acc")
        acc_s = f", holdout {acc*100:.1f}%" if isinstance(acc, (int, float)) else ""
        tier = (p.get("pricing") or {}).get("tier", p.get("status", "?"))
        lines.append(
            f"- `{p['name']}@{p['version']}` ({tier}) — {p['classes']} labels"
            f"{acc_s}, {floor_s}")
    return "\n".join(lines)


def hosted_llms():
    try:
        r = subprocess.run(["curl", "-fsS", "--max-time", "10", HOSTED_LLMS],
                           capture_output=True, text=True, timeout=15)
        if r.returncode == 0:
            return r.stdout.strip()
    except Exception:
        pass
    print("warn: hosted llms.txt unreachable — section omitted", file=sys.stderr)
    return None


def main():
    readme = read(README)
    # keep the README's substantive body: drop CI/badge noise lines
    readme = re.sub(r"!\[[^\]]*\]\([^)]*\)", "", readme)

    parts = [
        "# mtlm-router — llms-full.txt",
        "> Full-content companion to /llms.txt (generated by "
        "tools/render_llms_full.py — do not hand-edit). One fetch gives an "
        "agent the product README, the lane catalog, the pricing contract, "
        "and the hosted API's own machine doc.",
        "\n---\n\n# README (https://github.com/javimosch/mtlm-router)\n",
        readme,
        "\n---\n\n# Lane catalog (https://mtlm-router.intrane.fr/catalog.html)\n"
        "Free Apache-2.0 packs installable via tools/lane_install.py; "
        "registry at mtlm-heads/index.json.\n",
        lane_summary(),
        "\n---\n\n# Pricing & licensing (mtlm-heads/PRICING.md)\n",
        read(PRICING),
    ]

    hosted = hosted_llms()
    if hosted:
        parts += ["\n---\n\n# Hosted API — agent doc "
                  f"({HOSTED_LLMS}, fetched at build time)\n", hosted]

    with open(OUT, "w") as f:
        f.write("\n".join(parts) + "\n")
    print(f"wrote {OUT} ({os.path.getsize(OUT)} bytes)")


if __name__ == "__main__":
    main()
